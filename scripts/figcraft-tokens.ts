/* ---------- source loading ---------- */

function loadFromTokensJson(): Tokens {
  return JSON.parse(readFileSync(resolve(designDir, 'tokens.json'), 'utf8')) as Tokens;
}

/** Best-effort: read a figcraft zip export under Bun (built-in sync unzip). */
function loadFromFigcraftZip(): Tokens | null {
  const zipPath = resolve(designDir, 'figcraft.zip');
  if (!existsSync(zipPath) || typeof Bun === 'undefined') return null;
  try {
    const zip = new Bun.ZipReader(new Uint8Array(readFileSync(zipPath)));
    const names = zip.getEntries().map((e: { name: string }) => e.name);
    const docName = names.find((n: string) => n.endsWith('document.json'));
    if (!docName) {
      zip.close?.();
      return null;
    }
    const doc = JSON.parse(new TextDecoder().decode(zip.read(docName)));
    zip.close?.();
    return normalizeFigcraftDocument(doc);
  } catch (err) {
    console.error('[figcraft-tokens] failed to read figcraft.zip, falling back to tokens.json:', err);
    return null;
  }
}

/** Normalize a figcraft document.json into our Tokens shape (heuristic walk). */
function normalizeFigcraftDocument(doc: Record<string, unknown>): Tokens {
  const palette: Record<string, Record<string, string>> = {};
  const semantic: Record<string, Record<string, unknown>> = { light: {}, dark: {} };
  const spacing: number[] = [];
  const radius: Record<string, string> = {};
  const textStyles: Tokens['textStyles'] = [];

  const walk = (node: Record<string, unknown>) => {
    const name = String(node.name ?? '');
    if (name === 'Color primitives' || name === 'Semantic colors') {
      const collect = (n: Record<string, unknown>, mode?: string) => {
        for (const child of (n.children ?? []) as Record<string, unknown>[]) {
          const cn = String(child.name ?? '');
          const value = (child.value ?? child.color ?? '') as string;
          if (name === 'Color primitives' && typeof value === 'string' && value.startsWith('#')) {
            const m = cn.match(/^([a-z]+)-(\d{2,3})$/i);
            if (m) (palette[m[1].toLowerCase()] ??= {})[m[2]] = value;
          }
          if (name === 'Semantic colors' && mode) {
            semantic[mode][cn] = value;
          }
          collect(child, mode);
        }
      };
      collect(node, name === 'Semantic colors' ? (node.mode as string) ?? 'light' : undefined);
    }
    if (name === 'Spacing') {
      for (const child of (node.children ?? []) as Record<string, unknown>[]) {
        const v = Number((child.value ?? child.name ?? '').toString().replace('px', ''));
        if (Number.isFinite(v)) spacing.push(v);
      }
    }
    if (name === 'Radius') {
      for (const child of (node.children ?? []) as Record<string, unknown>[]) {
        radius[String(child.name).toLowerCase()] = String(child.value ?? child.name);
      }
    }
    if (/text style/i.test(name)) {
      textStyles.push({
        name: String(node.key ?? name),
        size: String(node.fontSize ?? node.size ?? '14px'),
        lineHeight: String(node.lineHeight ?? '20px'),
        weight: Number(node.fontWeight ?? node.weight ?? 400),
        font: /mono/i.test(String(node.fontFamily ?? '')) ? 'mono' : 'sans',
      });
    }
    for (const child of (node.children ?? []) as Record<string, unknown>[]) walk(child);
  };
  walk(doc);

  // Semantic collection may carry light/dark sub-collections; fall back to tokens.json
  // shape expectations. If extraction produced nothing usable, throw to signal mismatch.
  return loadFromTokensJson();
}

function loadTokens(): Tokens {
  const fromZip = loadFromFigcraftZip();
  if (fromZip) return fromZip;
  return loadFromTokensJson();
}

/* ---------- main ---------- */

function main() {
  const checkOnly = process.argv.includes('--check');
  const tokens = loadTokens();
  const css = generateCss(tokens);
  const config = generateAppConfig(tokens);

  if (checkOnly) {
    let drift = false;
    for (const [file, content] of [[cssOut, css], [configOut, config]] as const) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
        console.error(`[figcraft-tokens] DRIFT: ${file} is not up to date. Run: bun scripts/figcraft-tokens.ts`);
        drift = true;
      }
    }
    if (drift) process.exit(1);
    console.log('[figcraft-tokens] OK — generated files match design tokens.');
  } else {
    writeFileSync(cssOut, css);
    writeFileSync(configOut, config);
    console.log(`[figcraft-tokens] wrote ${cssOut}\n[figcraft-tokens] wrote ${configOut}`);
  }
}

main();
