/**
 * Generates Nexa design tokens from Nexa.figcraft into code.
 *
 * Source (first match wins):
 *  1. design/figcraft.zip  — raw figcraft export; document.json is read when
 *     running under Bun (built-in unzip). Used when design changes.
 *  2. design/tokens.json   — pre-extracted collections, committed to the repo.
 *     Used by CI and by environments without Bun.
 *
 * Output (deterministic — CI regenerates and fails on drift):
 *  - packages/ui/assets/css/tokens.css   (:root + .dark semantic vars, radius modes)
 *  - packages/ui/app.config.ts           (Nuxt UI theme: ui.colors + control sizes)
 *
 * Run: bun scripts/figcraft-tokens.ts | tsx scripts/figcraft-tokens.ts
 * Check: bun scripts/figcraft-tokens.ts --check
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const designDir = resolve(root, 'design');
const cssOut = resolve(root, 'packages/ui/assets/css/tokens.css');
const configOut = resolve(root, 'packages/ui/app.config.ts');

const ROLES = ['primary', 'secondary', 'success', 'info', 'warning', 'error'] as const;
type Role = (typeof ROLES)[number];

interface RoleSpec { base: string; text: string; hover: string; soft: number; 'soft-hover': number }
interface Semantic {
  bg: string; 'bg-muted': string; 'bg-elevated': string; 'bg-accented': string; 'bg-inverted': string;
  border: string; 'border-muted': string; 'border-accented': string; 'border-inverted': string;
  text: string; 'text-muted': string; 'text-toned': string; 'text-dimmed': string;
  'text-highlighted': string; 'text-inverted': string;
  'on-solid': string; ring: string; overlay: string; neutral: string; 'neutral-muted': string;
  roles: Record<Role, RoleSpec>;
}
interface Tokens {
  palette: Record<string, Record<string, string>>;
  semantic: { light: Semantic; dark: Semantic };
  spacing: number[];
  radius: Record<string, string>;
  controlHeights: Record<string, string>;
  iconSizes: number[];
  shadows: Record<string, string>;
  textStyles: { name: string; size: string; lineHeight: string; weight: number; font: string }[];
  uiColors: Record<string, string>;
}

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}
function rgbToHex(r: number, g: number, b: number): string {
  const c = (n: number) => Math.round(Math.max(0, Math.min(255, n))).toString(16).padStart(2, '0');
  return `#${c(r)}${c(g)}${c(b)}`;
}
/** Mix `fg` over `bg` at `alpha` (0..1). Deterministic hex output. */
function mix(fg: string, bg: string, alpha: number): string {
  const [r1, g1, b1] = hexToRgb(fg);
  const [r2, g2, b2] = hexToRgb(bg);
  return rgbToHex(r1 * alpha + r2 * (1 - alpha), g1 * alpha + g2 * (1 - alpha), b1 * alpha + b2 * (1 - alpha));
}

function roleVars(mode: Semantic, bg: string): string[] {
  const lines: string[] = [];
  for (const role of ROLES) {
    const r = mode.roles[role];
    lines.push(`  --ui-${role}: ${r.base};`);
    lines.push(`  --ui-${role}-text: ${r.text};`);
    lines.push(`  --ui-${role}-hover: ${r.hover};`);
    lines.push(`  --ui-${role}-soft: ${mix(r.base, bg, r.soft)};`);
    lines.push(`  --ui-${role}-soft-hover: ${mix(r.base, bg, r['soft-hover'])};`);
    lines.push(`  --ui-${role}-ring: ${r.base};`);
    lines.push(`  --ui-${role}-outline: ${r.base};`);
  }
  return lines;
}

function semanticBlock(mode: Semantic, selector: string): string {
  const roleBg = mode.bg;
  const base = [
    `  --ui-bg: ${mode.bg};`,
    `  --ui-bg-muted: ${mode['bg-muted']};`,
    `  --ui-bg-elevated: ${mode['bg-elevated']};`,
    `  --ui-bg-accented: ${mode['bg-accented']};`,
    `  --ui-bg-inverted: ${mode['bg-inverted']};`,
    `  --ui-border: ${mode.border};`,
    `  --ui-border-muted: ${mode['border-muted']};`,
    `  --ui-border-accented: ${mode['border-accented']};`,
    `  --ui-border-inverted: ${mode['border-inverted']};`,
    `  --ui-text: ${mode.text};`,
    `  --ui-text-muted: ${mode['text-muted']};`,
    `  --ui-text-toned: ${mode['text-toned']};`,
    `  --ui-text-dimmed: ${mode['text-dimmed']};`,
    `  --ui-text-highlighted: ${mode['text-highlighted']};`,
    `  --ui-text-inverted: ${mode['text-inverted']};`,
    `  --ui-on-solid: ${mode['on-solid']};`,
    `  --ui-ring: ${mode.ring};`,
    `  --ui-overlay: ${mode.overlay};`,
    `  --ui-neutral: ${mode.neutral};`,
    `  --ui-neutral-muted: ${mode['neutral-muted']};`,
  ];
  return `${selector} {\n${base.join('\n')}\n${roleVars(mode, roleBg).join('\n')}\n}`;
}

export function generateCss(t: Tokens): string {
  const header = `/* GENERATED by scripts/figcraft-tokens.ts from design tokens — do not edit by hand. */`;
  const radius = t.radius;
  const radiusModes = Object.entries(radius)
    .filter(([k]) => k !== 'default')
    .map(([k, v]) => `html[data-radius='${k}'] {\n  --ui-radius: ${v};\n}`)
    .join('\n');
  const shadows = Object.entries(t.shadows)
    .map(([k, v]) => `  --ui-shadow-${k}: ${v};`)
    .join('\n');
  return [
    header,
    '',
    ':root {',
    `  --ui-radius: ${radius.default};`,
    shadows,
    '}',
    '',
    semanticBlock(t.semantic.light, ':root'),
    '',
    semanticBlock(t.semantic.dark, '.dark'),
    '',
    radiusModes,
    '',
  ].join('\n');
}

