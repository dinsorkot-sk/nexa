<script setup lang="ts">
import type { FieldSpec } from '@nexa/types';

const props = withDefaults(defineProps<{
  field: FieldSpec;
  modelValue?: unknown;
  error?: string;
  hint?: string;
  disabled?: boolean;
  loading?: boolean;
}>(), { modelValue: undefined, error: '', hint: '', disabled: false, loading: false });

const emit = defineEmits<{ 'update:modelValue': [value: unknown] }>();

const { t } = useI18n();

const value = computed({
  get: () => props.modelValue,
  set: (v: unknown) => emit('update:modelValue', v),
});

const isReadOnly = computed(() => props.field.readOnly || ['autoNumber', 'formula', 'computed'].includes(props.field.logicalType));

const selectItems = computed(() => (props.field.options ?? []).map((o) => ({ label: o.label, value: o.value })));

const numberStep = computed(() => {
  const scale = props.field.scale ?? 0;
  return scale > 0 ? Math.pow(10, -scale) : 1;
});

const numberValue = computed<number>({
  get: () => Number(value.value ?? 0),
  set: (v: number) => emit('update:modelValue', v),
});

const dateValue = computed({
  get: () => (typeof value.value === 'string' && value.value ? new Date(value.value) : value.value as Date | undefined),
  set: (v: Date | undefined) => { value.value = v?.toISOString() ?? null; },
});

const datePart = computed(() => (typeof value.value === 'string' && value.value ? value.value.slice(0, 10) : ''));
const timePart = computed(() => (typeof value.value === 'string' && value.value ? value.value.slice(11, 16) : ''));

function setDateTime(part: 'date' | 'time', v: string) {
  const base = typeof value.value === 'string' && value.value ? value.value : '2026-01-01T00:00:00.000Z';
  const [d, t] = [base.slice(0, 10), base.slice(11, 16)];
  const nd = part === 'date' ? v : d;
  const nt = part === 'time' ? v : t;
  value.value = `${nd}T${nt}:00.000Z`;
}

function jsonText() {
  if (typeof value.value === 'string') return value.value;
  if (value.value === undefined || value.value === null || value.value === '') return '';
  try { return JSON.stringify(value.value, null, 2); } catch { return String(value.value); }
}

function setJson(text: string) {
  try {
    value.value = JSON.parse(text);
  } catch {
    value.value = text;
  }
}
</script>

<template>
  <UFormField :label="field.label" :required="field.required && !isReadOnly" :error="error" :hint="hint ?? field.description ?? ''" :disabled="disabled || isReadOnly">
    <!-- read-only calculated types -->
    <div v-if="isReadOnly" class="flex min-h-9 items-center rounded-md border border-default bg-[--ui-bg-muted] px-3 py-2">
      <span class="text-nexa-body text-muted">
        {{ value === undefined || value === null || value === '' ? t('fields.autoGenerated') : String(value) }}
      </span>
      <UIcon v-if="field.logicalType === 'formula' || field.logicalType === 'computed'" name="i-lucide-function-square" class="ms-2 size-4 text-dimmed" />
    </div>

    <!-- text-like -->
    <UInput
      v-else-if="['text', 'email', 'phone', 'url'].includes(field.logicalType)"
      :model-value="value as string"
      :type="field.logicalType === 'email' ? 'email' : field.logicalType === 'phone' ? 'tel' : field.logicalType === 'url' ? 'url' : 'text'"
      :placeholder="t(`fields.placeholder.${field.logicalType}`)"
      :disabled="disabled"
      class="w-full"
      @update:model-value="emit('update:modelValue', $event)"
    >
      <template v-if="field.logicalType === 'email'" #leading>
        <UIcon name="i-lucide-mail" class="size-4" />
      </template>
      <template v-else-if="field.logicalType === 'phone'" #leading>
        <UIcon name="i-lucide-phone" class="size-4" />
      </template>
      <template v-else-if="field.logicalType === 'url'" #leading>
        <UIcon name="i-lucide-link" class="size-4" />
      </template>
      <template v-if="loading" #trailing>
        <UIcon name="i-lucide-loader-circle" class="size-4 animate-spin text-muted" />
      </template>
    </UInput>

    <!-- long text -->
    <UTextarea
      v-else-if="field.logicalType === 'longText'"
      :model-value="value as string"
      :placeholder="t('fields.placeholder.longText')"
      :disabled="disabled"
      autoresize
      class="w-full"
      @update:model-value="emit('update:modelValue', $event)"
    />

    <!-- numbers -->
    <div v-else-if="['integer', 'number', 'decimal', 'currency', 'percentage'].includes(field.logicalType)" class="flex items-center gap-2">
      <UInputNumber
        v-if="field.logicalType !== 'currency' && field.logicalType !== 'percentage'"
        v-model="numberValue"
        :step="field.logicalType === 'integer' ? 1 : numberStep"
        :disabled="disabled"
        :placeholder="t('fields.placeholder.number')"
        class="w-full"
      />
      <UInputNumber
        v-else
        v-model="numberValue"
        :step="numberStep"
        :disabled="disabled"
        :placeholder="t('fields.placeholder.number')"
        class="w-full"
      >
        <template v-if="field.logicalType === 'currency'" #leading>฿</template>
        <template v-else #trailing>%</template>
      </UInputNumber>
    </div>

    <!-- boolean -->
    <USwitch
      v-else-if="field.logicalType === 'boolean'"
      :model-value="Boolean(value)"
      :label="field.label"
      :disabled="disabled"
      @update:model-value="emit('update:modelValue', $event)"
    />

    <!-- date / time -->
    <UInputDate
      v-else-if="field.logicalType === 'date'"
      v-model="dateValue"
      :disabled="disabled"
      :placeholder="t('fields.placeholder.date')"
      class="w-full"
    />
    <div v-else-if="field.logicalType === 'datetime'" class="flex gap-2">
      <UInputDate v-model="dateValue" :disabled="disabled" class="flex-1" />
      <UInputTime :model-value="timePart" :disabled="disabled" class="w-32" @update:model-value="setDateTime('time', $event)" />
    </div>
    <UInputTime
      v-else-if="field.logicalType === 'time'"
      :model-value="timePart"
      :disabled="disabled"
      placeholder="HH:mm"
      class="w-full"
      @update:model-value="setDateTime('time', $event)"
    />

    <!-- choice -->
    <USelect
      v-else-if="field.logicalType === 'select'"
      :model-value="value as string"
      :items="selectItems"
      :disabled="disabled"
      :placeholder="t('fields.placeholder.select')"
      class="w-full"
      @update:model-value="emit('update:modelValue', $event)"
    />
    <USelectMenu
      v-else-if="field.logicalType === 'multiSelect'"
      :model-value="value as string[]"
      :items="selectItems"
      multiple
      :disabled="disabled"
      :placeholder="t('fields.placeholder.multiSelect')"
      class="w-full"
      @update:model-value="emit('update:modelValue', $event)"
    />

    <!-- reference -->
    <NxReferenceSelect
      v-else-if="field.logicalType === 'reference'"
      :field="field"
      :model-value="value as string"
      :disabled="disabled"
      :loading="loading"
      @update:model-value="emit('update:modelValue', $event)"
    />

    <!-- media (URL only in v1) -->
    <UInput
      v-else-if="field.logicalType === 'file' || field.logicalType === 'image'"
      :model-value="value as string"
      type="url"
      :placeholder="t('fields.placeholder.url')"
      :disabled="disabled"
      class="w-full"
      @update:model-value="emit('update:modelValue', $event)"
    >
      <template #leading>
        <UIcon name="i-lucide-link" class="size-4" />
      </template>
    </UInput>
    <div v-if="field.logicalType === 'image' && typeof value === 'string' && value" class="mt-2">
      <img :src="value" :alt="field.label" class="h-24 w-full rounded-md border border-default object-cover" @error="($event.target as HTMLImageElement).style.display = 'none'">
    </div>

    <!-- json -->
    <UTextarea
      v-else-if="field.logicalType === 'json'"
      :model-value="jsonText()"
      :placeholder="t('fields.placeholder.json')"
      :disabled="disabled"
      class="w-full font-mono text-nexa-mono-small"
      @update:model-value="setJson($event)"
    />

    <div v-else class="rounded-md border border-dashed border-default p-3 text-nexa-small text-muted">
      {{ field.logicalType }}
    </div>
  </UFormField>
</template>
